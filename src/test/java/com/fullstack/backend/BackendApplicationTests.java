package com.fullstack.backend;

import com.fullstack.backend.dto.StudentSearchResult;
import com.fullstack.backend.exception.DuplicateRollNumberException;
import com.fullstack.backend.model.Batch;
import com.fullstack.backend.model.Student;
import com.fullstack.backend.repository.BatchRepository;
import com.fullstack.backend.service.BatchService;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
class BackendApplicationTests {

    @Autowired
    private BatchRepository batchRepository;

    @Autowired
    private BatchService batchService;

    @Test
    void contextLoads() {
        assertNotNull(batchRepository);
        assertNotNull(batchService);
    }

    @Test
    void testBatchAndStudentLifecycle() {
        String testBatchName1 = "TEST-CSE-A-" + System.currentTimeMillis();
        String testBatchName2 = "TEST-CSE-B-" + System.currentTimeMillis();
        String testRoll1 = "TEST-ROLL-" + System.currentTimeMillis();
        String testRoll2 = "TEST-ROLL-2-" + System.currentTimeMillis();

        Batch savedBatch1 = null;
        Batch savedBatch2 = null;

        try {
            // 1. Create Batch 1
            Batch batch1 = new Batch(testBatchName1, "Full Stack Java", "2026-11-01");
            savedBatch1 = batchService.createBatch(batch1);
            assertNotNull(savedBatch1.getId(), "Batch ID must be generated by MongoDB");
            assertEquals(testBatchName1, savedBatch1.getBatchName());
            assertEquals(0, savedBatch1.getStudentCount());

            // 2. Add Student 1 to Batch 1
            Student s1 = new Student("Alice Johnson", testRoll1);
            Batch updatedBatch1 = batchService.addStudentToBatch(savedBatch1.getId(), s1);
            assertEquals(1, updatedBatch1.getStudentCount());
            assertEquals(1, batchService.getStudentCount(savedBatch1.getId()));
            assertEquals("Alice Johnson", updatedBatch1.getStudents().get(0).getName());

            // 3. Add Student 2 to Batch 1
            Student s2 = new Student("Bob Smith", testRoll2);
            updatedBatch1 = batchService.addStudentToBatch(savedBatch1.getId(), s2);
            assertEquals(2, updatedBatch1.getStudentCount());

            // 4. Duplicate roll number in same batch must be rejected
            final String batch1Id = savedBatch1.getId();
            Student duplicateRoll = new Student("Charlie Brown", testRoll1);
            DuplicateRollNumberException ex = assertThrows(DuplicateRollNumberException.class, () -> {
                batchService.addStudentToBatch(batch1Id, duplicateRoll);
            }, "Duplicate roll number within the same batch must throw DuplicateRollNumberException");
            assertEquals("This roll number already exists in this batch.", ex.getMessage());

            // 5. Same roll number in a different batch MUST be allowed
            Batch batch2 = new Batch(testBatchName2, "Cloud Computing", "2026-12-01");
            savedBatch2 = batchService.createBatch(batch2);
            Student sInBatch2 = new Student("Alice Senior", testRoll1);
            Batch updatedBatch2 = batchService.addStudentToBatch(savedBatch2.getId(), sInBatch2);
            assertEquals(1, updatedBatch2.getStudentCount());

            // 6. Search across all batches by roll number
            List<StudentSearchResult> searchResults = batchService.searchByRollNumber(testRoll1);
            assertEquals(2, searchResults.size(), "Should find testRoll1 across both batches");

            // 7. Search for Bob by roll number
            List<StudentSearchResult> bobResults = batchService.searchByRollNumber(testRoll2);
            assertEquals(1, bobResults.size());
            assertEquals("Bob Smith", bobResults.get(0).getName());
            assertEquals(testBatchName1, bobResults.get(0).getBatchName());

        } finally {
            // Clean up ONLY the test batches created in this test, never touching user records
            if (savedBatch1 != null && savedBatch1.getId() != null) {
                batchRepository.deleteById(savedBatch1.getId());
            }
            if (savedBatch2 != null && savedBatch2.getId() != null) {
                batchRepository.deleteById(savedBatch2.getId());
            }
        }
    }
}
